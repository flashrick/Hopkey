// Regenerates src/Hopkey.Core/Pinyin/pinyin-data.txt from mozillazg/pinyin-data (MIT).
//   1. Download https://raw.githubusercontent.com/mozillazg/pinyin-data/master/pinyin.txt
//   2. dotnet run tools/gen-pinyin.cs -- <path-to-pinyin.txt> src/Hopkey.Core/Pinyin/pinyin-data.txt
// Output: one line per CJK char in U+4E00..U+9FFF: "<char> reading1,reading2" (toneless, ü → v, most common first).
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

if (args.Length != 2) { Console.Error.WriteLine("usage: gen-pinyin <pinyin.txt> <out>"); return 1; }
var line = new Regex(@"^U\+([0-9A-F]{4,5}):\s*([^#]+)", RegexOptions.Compiled);
var sb = new StringBuilder();
sb.Append("# Generated by tools/gen-pinyin.cs from https://github.com/mozillazg/pinyin-data (MIT, see pinyin-data.LICENSE.txt)\n");
int count = 0;
foreach (var raw in File.ReadLines(args[0], Encoding.UTF8))
{
    var m = line.Match(raw);
    if (!m.Success) continue;
    int cp = int.Parse(m.Groups[1].Value, NumberStyles.HexNumber);
    if (cp < 0x4E00 || cp > 0x9FFF) continue;
    var readings = new List<string>();
    foreach (var r in m.Groups[2].Value.Split(',', StringSplitOptions.TrimEntries | StringSplitOptions.RemoveEmptyEntries))
    {
        var t = Toneless(r);
        if (t.Length > 0 && !readings.Contains(t)) readings.Add(t);
    }
    if (readings.Count == 0) continue;
    sb.Append((char)cp).Append(' ').Append(string.Join(',', readings)).Append('\n');
    count++;
}
File.WriteAllText(args[1], sb.ToString(), new UTF8Encoding(false));
Console.WriteLine($"{count} chars → {args[1]}");
return 0;

static string Toneless(string s)
{
    var sb = new StringBuilder(s.Length);
    foreach (var c in s.Normalize(NormalizationForm.FormD))
    {
        if (CharUnicodeInfo.GetUnicodeCategory(c) == UnicodeCategory.NonSpacingMark)
        {
            if (c == '̈' && sb.Length > 0 && sb[^1] == 'u') sb[^1] = 'v'; // ü
            continue;
        }
        char l = char.ToLowerInvariant(c);
        if (l is >= 'a' and <= 'z') sb.Append(l);
    }
    return sb.ToString();
}
